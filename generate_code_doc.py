def add_file_section(pdf: FPDF, path: str, blurb: str, annotations):
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 15)
    pdf.set_text_color(*HEADING_COLOR)
    pdf.cell(0, 10, safe(path), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*EXPLAIN_COLOR)
    pdf.multi_cell(0, 5.5, safe(blurb), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(3)

    full_path = REPO_DIR / path
    lines = full_path.read_text(encoding="utf-8").splitlines()

    for start, end, explanation in annotations:
        code_block = "\n".join(lines[start - 1:end])
        label = f"L{start}" if start == end else f"L{start}-{end}"

        pdf.set_font("Courier", "", 8.5)
        pdf.set_text_color(*HEADING_COLOR)
        pdf.set_fill_color(*CODE_FILL)
        pdf.multi_cell(
            0,
            4.2,
            safe(f"{label}:\n{code_block}" if code_block.strip() else f"{label}: (blank)"),
            fill=True,
            new_x=XPos.LMARGIN,
            new_y=YPos.NEXT,
        )

        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(*EXPLAIN_COLOR)
        pdf.multi_cell(0, 5, safe(f"-> {explanation}"), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(2.5)


def add_closing_section(pdf: FPDF):
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 15)
    pdf.set_text_color(*HEADING_COLOR)
    pdf.cell(0, 10, safe("Generated files (not walked through line-by-line)"), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(2)

    for name, note in NOT_WALKED_THROUGH:
        pdf.set_font("Courier", "B", 10)
        pdf.set_text_color(*HEADING_COLOR)
        pdf.cell(0, 6, safe(name), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_font("Helvetica", "", 9.5)
        pdf.set_text_color(*EXPLAIN_COLOR)
        pdf.multi_cell(0, 5, safe(note), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(2)


def main():
    pdf = FPDF(orientation="L", format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.set_margins(left=14, top=14, right=14)

    add_title_page(pdf)
    for f in FILES:
        add_file_section(pdf, f["path"], f["blurb"], f["annotations"])
    add_closing_section(pdf)

    pdf.output(str(OUT_PATH))
    print(f"RESULT: wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
