_ASCII_SUBSTITUTIONS = {
    "—": "--",  # em dash
    "–": "-",   # en dash
    "‘": "'",
    "’": "'",
    "“": '"',
    "”": '"',
}


def safe(text: str) -> str:
    """Core PDF fonts (Helvetica/Courier) only support latin-1 -- swap common
    unicode punctuation for its ASCII equivalent first, so code containing it
    (e.g. scrape.py's em dash) renders as the intended character rather than
    a literal '?'."""
    text = text or ""
    for uni, ascii_equiv in _ASCII_SUBSTITUTIONS.items():
        text = text.replace(uni, ascii_equiv)
    return text.encode("latin-1", "replace").decode("latin-1")


